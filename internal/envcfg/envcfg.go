// Package envcfg — разбор настроек из окружения.
//
// Пакет существует ради одной функции: её зовут из трёх разных пакетов
// (сервер, комнаты, профили), каждый читает свои переменные, и заводить ради
// четырёх строк копию в каждом — верный способ развести поведение.
package envcfg

import "fmt"

// ParseInt разбирает целое из строки окружения.
//
// Намеренно Sscanf, а не strconv.Atoi: так ведёт себя конфигурация с самого
// начала проекта, и на боевых машинах в переменных встречается хвост вроде
// "8090 # порт", который сейчас молча отбрасывается. Смена на Atoi превратила
// бы такие настройки в дефолт при ближайшем рестарте.
func ParseInt(s string) (int, error) {
	var n int
	_, err := fmt.Sscanf(s, "%d", &n)
	return n, err
}
