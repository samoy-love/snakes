/* Чтение одной клетки сетки территорий.

   F5 «Реклейм»: сервер отдаёт остывающую территорию тем же полем сетки, но
   со старшим битом 0x8000 — значение читается как «клетка ничья, но её ещё
   может вернуть игрок (v & 0x7FFF)». Обе функции обязаны снимать флаг, иначе
   0x8000|n читается как несуществующий игрок и клетка становится серой.

   Отдельный модуль на две строки нужен потому, что читателей у них трое —
   отрисовка поля, миникарта и разбор дельты сетки, — и разъехаться в
   трактовке старшего бита им нельзя. */

const COOL_OWNER_FLAG = 0x8000;

export function gridCellOwner(v) {
  return (Number(v) || 0) & 0x7fff;
}

export function gridCellIsCooling(v) {
  return ((Number(v) || 0) & COOL_OWNER_FLAG) !== 0;
}
