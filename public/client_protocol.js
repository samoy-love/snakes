/* Разбор бинарного протокола ROI-обновлений (msgType === 2, handleStateBinary
   в client.js): выбор размера записи игрока в кадре.

   Сервер эволюционировал формат четыре раза, не меняя msgType — новые поля
   (щит, бот-флаг, экипировка) дописывались в конец записи игрока, и старый
   клиент должен понимать и старые, и новые кадры. Единственный сигнал версии —
   сколько байт реально осталось в буфере: клиент пробует самый длинный формат
   и спускается вниз, пока запись не влезет. Раньше это было развёрнуто вручную
   вложенными if внутри handleStateBinary и проверялось только грепом исходника
   (см. §6.4 отчёта разведки от 2026-08-05) — здесь то же решение как чистая
   функция с тестами на сетке значений. */

// [v4, v3, v2, v1] — байт на запись игрока, по убыванию, для каждой версии
// протокола. Порядок значим: пробуем от новой версии к старой.
export const PLAYER_RECORD_SIZES = [21, 20, 15, 14];

// rx/ry/rw/rh (4 × uint16 = 8) + lenDG/lenDT (2 × uint32 = 8), которые идут
// после списка игроков в том же кадре.
export const ROI_TAIL_BYTES = 16;

/** Размер записи игрока (в байтах), который влезает в оставшийся буфер, либо
    null, если не влезает даже самый старый (v1) формат — кадр обрезан. */
export function pickPlayerRecordSize(availableBytes, playerCount) {
  const avail = Number(availableBytes) || 0;
  const pc = Number(playerCount) || 0;
  for (const size of PLAYER_RECORD_SIZES) {
    if (avail >= pc * size + ROI_TAIL_BYTES) return size;
  }
  return null;
}
